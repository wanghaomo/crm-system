/**
 * 解析 RAW 数据为级联树。
 * @returns n-cascader 需要的 options 树
 */
export function buildRegionOptions(): RegionNode[] {
    const tree: RegionNode[] = [];
    REGION_RAW.forEach((provinceRaw) => {
        const [provinceName, rest] = provinceRaw.split(":");
        const provinceValue = provinceName.includes("|") ? provinceName : provinceName;
        const provinceLabel = provinceValue;
        const isMunicipality = !provinceRaw.includes("|");
        const children: RegionNode[] = [];

        if (isMunicipality) {
            // 直辖市：省下直接挂区县（两级）
            rest.split(",").forEach((districtName) => {
                children.push({ label: districtName, value: `${provinceLabel}/${districtName}` });
            });
        } else {
            // 普通省份：省 -> 市 -> 区县（三级）
            rest.split(";").forEach((cityRaw) => {
                const [cityName, districtStr] = cityRaw.split(":");
                const cityChildren: RegionNode[] = (districtStr || "")
                    .split(",")
                    .filter(Boolean)
                    .map((districtName) => ({
                        label: districtName,
                        value: `${provinceLabel}/${cityName}/${districtName}`,
                    }));
                children.push({ label: cityName, value: `${provinceLabel}/${cityName}`, children: cityChildren });
            });
        }
        tree.push({ label: provinceLabel, value: provinceLabel, children });
    });
    return tree;
}
